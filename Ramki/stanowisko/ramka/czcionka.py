def glif(znak: str) -> tuple:
    """Wiersze znaku (7 napisow po 5 znakow)."""
    return ZNAKI.get(znak.upper(), ZNAKI["?"])


def szerokosc(tekst: str) -> int:
    """Szerokosc napisu w pikselach (bez odstepu po ostatnim znaku)."""
    if not tekst:
        return 0
    return len(tekst) * (SZER + ODSTEP) - ODSTEP
